/**
 * `npm run check:projects`
 *
 * Every TypeScript file must belong to a TypeScript project.
 *
 * A file that no `tsconfig.json` includes still opens fine in an editor — it
 * lands in an *inferred* project, which has no path mappings, no Node types and
 * default module resolution. It lights up red while `npm run typecheck` passes
 * clean, because the typecheck never looked at it. That happened here to all
 * twenty test files and to `vitest.config.ts`, and it hid a test calling a
 * six-argument function with four.
 *
 * The check is the same one a person would do by hand: ask each project what
 * files it sees, and compare that against what is on disk.
 */

import { execFileSync } from 'node:child_process';
import { readdirSync, statSync } from 'node:fs';
import { join, relative, resolve } from 'node:path';

/** Projects that between them must cover everything. */
const PROJECTS = ['tsconfig.json', 'apps/editor/tsconfig.json', 'apps/play/tsconfig.json'];

/** Directories that hold no source of ours. */
const SKIP = new Set(['node_modules', '.next', 'dist', '.git', 'schema', 'docs']);

/** Generated by tooling, and not ours to place in a project. */
const GENERATED = new Set(['apps/editor/next-env.d.ts', 'apps/play/next-env.d.ts']);

const root = resolve(process.cwd());

function sourceFiles(dir: string, found: string[] = []): string[] {
  for (const entry of readdirSync(dir)) {
    if (SKIP.has(entry) || entry.startsWith('.')) continue;

    const path = join(dir, entry);
    if (statSync(path).isDirectory()) {
      sourceFiles(path, found);
    } else if (entry.endsWith('.ts') || entry.endsWith('.tsx')) {
      found.push(relative(root, path));
    }
  }
  return found;
}

/** What a project actually sees, which is the only authority worth asking. */
function filesSeenBy(project: string): Set<string> {
  const out = execFileSync(
    'npx',
    ['tsc', '-p', project, '--listFilesOnly', '--noEmit'],
    { encoding: 'utf8', maxBuffer: 64 * 1024 * 1024, cwd: root },
  );

  const seen = new Set<string>();
  for (const line of out.split('\n')) {
    const path = line.trim();
    if (!path || path.includes('node_modules')) continue;
    seen.add(relative(root, path));
  }
  return seen;
}

function main(): number {
  const onDisk = sourceFiles(root).filter((path) => !GENERATED.has(path));

  const covered = new Set<string>();
  for (const project of PROJECTS) {
    for (const path of filesSeenBy(project)) covered.add(path);
  }

  const orphans = onDisk.filter((path) => !covered.has(path)).sort();

  if (orphans.length > 0) {
    process.stderr.write(
      `\n  ${orphans.length} file(s) belong to no TypeScript project:\n\n`
      + orphans.map((path) => `    ${path}\n`).join('')
      + '\n  They will show errors in an editor that the typecheck cannot see.\n'
      + `  Add them to one of: ${PROJECTS.join(', ')}\n\n`,
    );
    return 1;
  }

  process.stdout.write(`  ✓ all ${onDisk.length} TypeScript files are in a project\n`);
  return 0;
}

process.exit(main());
