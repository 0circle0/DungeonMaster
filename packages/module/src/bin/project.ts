/**
 * `npm run project -- split <module>` / `build <module>`
 *
 * Turns a module into a directory of files, and back. `split` is a one-time
 * import: it reads `module.json` and writes `project/`. `build` is the step
 * that runs afterwards forever, reading `project/` and writing `module.json`.
 *
 * The safety property is that `build` never invents anything. Splitting and
 * rebuilding a module reproduces its file byte for byte — checked for all four
 * shipped modules in `project.test.ts` — so adopting the format is not a
 * rewrite of the content, and abandoning it is `rm -r project/`.
 *
 * `split` refuses to overwrite an existing `project/` without `--force`, and
 * `build` refuses to write a `module.json` that does not compile. Both write
 * whole files rather than patching, so a partial run leaves nothing half-done
 * beyond the file it was on.
 */

import { readFileSync, writeFileSync, mkdirSync, existsSync, readdirSync, rmSync, statSync } from 'node:fs';
import { gunzipSync } from 'node:zlib';
import { dirname, join, relative, resolve } from 'node:path';
import { splitProject, joinProject } from '../project.js';
import type { Prefab, StyleTables } from '../prefab.js';
import { unbundleModule } from '../bundle.js';
import type { ProjectManifest } from '../project.js';
import { lintModule, formatDiagnostics } from '../diagnostics/lint.js';
import { assembleMapFolders, formatMapIssues } from '../load.js';

const MANIFEST = 'project.json';

function usage(): number {
  process.stderr.write(
    'usage: npm run project -- <split|build> <module-dir> [--force]\n' +
      '       npm run project -- unpack <bundle.json[.gz]> <module-dir> [--force]\n' +
      '  split   module.json -> project/   (one file per entry)\n' +
      '  build   project/   -> module.json\n' +
      '  unpack  a bundle exported from the studio -> project/ and maps/\n',
  );
  return 2;
}

/**
 * The prefabs and style tables a project's recipes expand against.
 *
 * Read here rather than by `joinProject`, which has no filesystem — and read at
 * all only because a compressed project's entry files are recipes. A project
 * with no `prefabs/` gets an empty pair and builds exactly as it always did.
 */
function readAuthoringFor(projectDir: string): { prefabs: Prefab[]; style: StyleTables } {
  const prefabDir = join(projectDir, 'prefabs');
  const prefabs: Prefab[] = [];
  if (existsSync(prefabDir)) {
    for (const file of readdirSync(prefabDir).sort()) {
      if (!file.endsWith('.json') || file === 'instances.json') continue;
      prefabs.push(JSON.parse(readFileSync(join(prefabDir, file), 'utf8')) as Prefab);
    }
  }

  const stylePath = join(projectDir, 'style.json');
  const style = existsSync(stylePath)
    ? (JSON.parse(readFileSync(stylePath, 'utf8')) as StyleTables)
    : {};

  return { prefabs, style };
}

/** Every file under a directory, by path relative to it. */
function readTree(root: string): Record<string, string> {
  const out: Record<string, string> = {};
  const walk = (dir: string): void => {
    for (const entry of readdirSync(dir)) {
      const path = join(dir, entry);
      if (statSync(path).isDirectory()) walk(path);
      else if (path.endsWith('.json')) out[relative(root, path).split('\\').join('/')] = readFileSync(path, 'utf8');
    }
  };
  walk(root);
  return out;
}

/**
 * Refuse to give a generated module a second source of truth.
 *
 * A generator that overwrites `module.json` rather than merging into it makes a
 * `project/` beside it a third representation of the same world, silently stale
 * from the next run onwards. One source of truth per file.
 *
 * Aurendel and core_fantasy have since been through exactly this door — their
 * generators are retired and their `project/` trees are the source now, so the
 * marker files are still on disk and this correctly stops saying anything about
 * them, because a module that already *has* a `project/` has made its choice.
 * The hazard moved rather than went away: it is now somebody re-running a
 * retired generator, and the refusal for that lives at the top of the generator
 * itself.
 */
function generatedElsewhere(moduleDir: string): string | null {
  if (existsSync(join(moduleDir, 'project'))) return null;
  for (const marker of ['src/build.py', 'gen_core.py']) {
    if (existsSync(join(moduleDir, marker))) return marker;
  }
  return null;
}

function split(moduleDir: string, force: boolean): number {
  const generator = generatedElsewhere(moduleDir);
  if (generator && !force) {
    process.stderr.write(
      `✗ ${moduleDir} is generated by ${generator}, which overwrites module.json.\n` +
        '  A project/ beside it would be stale from the next build onwards.\n' +
        '  Pass --force if you are retiring the generator.\n',
    );
    return 1;
  }

  const source = join(moduleDir, 'module.json');
  if (!existsSync(source)) {
    process.stderr.write(`✗ ${source} does not exist\n`);
    return 1;
  }

  const projectDir = join(moduleDir, 'project');
  if (existsSync(projectDir) && !force) {
    process.stderr.write(`✗ ${projectDir} already exists — pass --force to replace it\n`);
    return 1;
  }

  const text = readFileSync(source, 'utf8');
  const doc = JSON.parse(text) as Record<string, unknown>;
  const result = splitProject(doc);

  // Verified before anything is written: if the round trip is not exact, the
  // split is not safe to adopt and saying so beats leaving a directory behind.
  const check = joinProject(result.manifest, result.files);
  const rebuilt = `${JSON.stringify(check.document, null, 2)}\n`;
  if (check.issues.length > 0 || rebuilt !== text) {
    process.stderr.write(`✗ ${moduleDir}: splitting it would not rebuild the same file — not written\n`);
    for (const issue of check.issues.slice(0, 5)) process.stderr.write(`  ${issue.message}\n`);
    return 1;
  }

  rmSync(projectDir, { recursive: true, force: true });
  mkdirSync(projectDir, { recursive: true });
  writeFileSync(join(projectDir, MANIFEST), `${JSON.stringify(result.manifest, null, 2)}\n`);
  for (const [file, contents] of Object.entries(result.files)) {
    const target = join(projectDir, file);
    mkdirSync(dirname(target), { recursive: true });
    writeFileSync(target, contents);
  }

  const count = Object.keys(result.files).length;
  process.stdout.write(`✓ ${projectDir} — ${count} files, and it rebuilds ${source} exactly\n`);
  return 0;
}

function build(moduleDir: string): number {
  const projectDir = join(moduleDir, 'project');
  if (!existsSync(projectDir)) {
    process.stderr.write(`✗ ${projectDir} does not exist — run \`split\` first\n`);
    return 1;
  }

  const files = readTree(projectDir);
  const manifestText = files[MANIFEST];
  if (manifestText === undefined) {
    process.stderr.write(`✗ ${join(projectDir, MANIFEST)} is missing\n`);
    return 1;
  }
  delete files[MANIFEST];

  const manifest = JSON.parse(manifestText) as ProjectManifest;
  const { document, issues } = joinProject(manifest, files, readAuthoringFor(projectDir));
  if (issues.length > 0) {
    process.stderr.write(`✗ ${projectDir} — ${issues.length} problem(s)\n`);
    for (const issue of issues.slice(0, 10)) process.stderr.write(`  ${issue.message}\n`);
    return 1;
  }

  // A project that does not compile is a build that must not land: `module.json`
  // is what the game loads, and a broken one is discovered three rooms in.
  //
  // Checked against the *assembled* document — static maps live in
  // `maps/<id>/` folders, so the raw form a module is written as has fourteen
  // references nothing has resolved yet. The raw form is still what gets
  // written; assembly is a reading step, not a build product.
  const text = `${JSON.stringify(document, null, 2)}\n`;
  const assembled = assembleMapFolders(document, moduleDir);
  if (assembled.issues.length > 0) {
    process.stderr.write(`✗ ${moduleDir} — ${assembled.issues.length} map problem(s)\n`);
    process.stderr.write(`${formatMapIssues(assembled.issues)}\n`);
    return 1;
  }
  const lint = lintModule(document, { assembled: assembled.doc });
  const errors = lint.diagnostics.filter((d) => d.severity === 'error');
  if (errors.length > 0) {
    process.stderr.write(`✗ ${projectDir} — ${errors.length} error(s), not written\n\n`);
    process.stderr.write(`${formatDiagnostics(errors.slice(0, 10), process.stdout.isTTY === true)}\n`);
    return 1;
  }

  const target = join(moduleDir, 'module.json');
  const before = existsSync(target) ? readFileSync(target, 'utf8') : null;
  writeFileSync(target, text);

  const changed = before === null ? 'created' : before === text ? 'unchanged' : 'updated';
  process.stdout.write(`✓ ${target} — ${changed}${lint.compiled ? ` (hash ${lint.compiled.hash})` : ''}\n`);
  return 0;
}

/**
 * A bundle the studio exported, back into the tree it came from.
 *
 * The studio cannot hand over a directory, so it writes one gzipped file of
 * path-to-contents. This is the other end of that, and it writes exactly what
 * the bundle says — no merging, because a partial write is how two
 * representations of one world start disagreeing.
 *
 * Authoring files are left alone: `prefabs/`, `style.json` and `contract.json`
 * are not produced by any document, so a bundle never carries them and clearing
 * them here would delete work nothing else holds.
 */
function unpack(bundlePath: string, moduleDir: string, force: boolean): number {
  if (!existsSync(bundlePath)) {
    process.stderr.write(`✗ ${bundlePath} does not exist\n`);
    return 1;
  }

  const bytes = readFileSync(bundlePath);
  const text = bytes[0] === 0x1f && bytes[1] === 0x8b
    ? gunzipSync(bytes).toString('utf8')
    : bytes.toString('utf8');

  let parsed: { files?: Record<string, string> };
  try {
    parsed = JSON.parse(text) as { files?: Record<string, string> };
  } catch (err) {
    process.stderr.write(`✗ ${bundlePath}: ${(err as Error).message}\n`);
    return 1;
  }

  const files = parsed.files;
  if (!files || typeof files !== 'object') {
    process.stderr.write(`✗ ${bundlePath} carries no files\n`);
    return 1;
  }

  // Proven before anything is written, the same gate `split` uses: a bundle
  // that does not rebuild is one nobody wants half-applied.
  const { document, issues } = unbundleModule(files);
  if (!document || issues.length > 0) {
    process.stderr.write(`✗ ${bundlePath} does not rebuild a module\n`);
    for (const issue of issues) process.stderr.write(`  ${issue.file}: ${issue.message}\n`);
    return 1;
  }

  const projectDir = join(moduleDir, 'project');
  if (existsSync(projectDir) && !force) {
    process.stderr.write(
      `✗ ${projectDir} already exists.\n  Pass --force to replace what is there.\n`,
    );
    return 1;
  }

  for (const [path, contents] of Object.entries(files)) {
    const target = join(moduleDir, path);
    mkdirSync(dirname(target), { recursive: true });
    writeFileSync(target, contents);
  }

  process.stdout.write(
    `✓ ${moduleDir} — ${Object.keys(files).length} files unpacked; ` +
      'run `npm run project -- build` to rebuild module.json\n',
  );
  return 0;
}

function main(): number {
  const args = process.argv.slice(2).filter((arg) => arg !== '--force');
  const [command, arg, second] = args;
  if (!command || !arg) return usage();
  const force = process.argv.includes('--force');

  if (command === 'unpack') {
    if (!second) return usage();
    return unpack(resolve(arg), resolve(second), force);
  }

  const moduleDir = resolve(arg);
  if (command === 'split') return split(moduleDir, force);
  if (command === 'build') return build(moduleDir);
  return usage();
}

process.exit(main());
